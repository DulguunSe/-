def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

def write(folder, idx):
    os.makedirs(f"{RES}/{folder}", exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<resources xmlns:tools="http://schemas.android.com/tools">']
    for k, v in S.items():
        attrs = ' translatable="false"' if (k == "ok" and idx == 0) else ""
        out.append(f'    <string name="{k}"{attrs}>{esc(v[idx])}</string>')
    for k, (en, mn) in P.items():
        out.append(f'    <plurals name="{k}">')
        if idx == 0:
            out.append(f'        <item quantity="one">{esc(en[0])}</item>')
            out.append(f'        <item quantity="other">{esc(en[1])}</item>')
        else:
            out.append(f'        <item quantity="one">{esc(mn)}</item>')
            out.append(f'        <item quantity="other">{esc(mn)}</item>')
        out.append("    </plurals>")
    for k, v in A.items():
        out.append(f'    <string-array name="{k}">')
        for item in v[idx]:
            out.append(f"        <item>{esc(item)}</item>")
        out.append("    </string-array>")
    out.append("</resources>")
    open(f"{RES}/{folder}/strings.xml", "w").write("\n".join(out) + "\n")

